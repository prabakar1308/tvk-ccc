/**
 * Deterministic string hash for consistent geometric boundary seeding.
 */
function hashString(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = ((hash << 5) - hash) + str.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
}

/**
 * Dynamically calculates an organic, realistic administrative boundary polygon
 * for ANY area in MASTER_AREAS_DATA (and any custom areas).
 *
 * Factors in:
 * 1. Center coordinates [lat, lng]
 * 2. Associated Kilais and Polling Booths (dynamically encompasses all points)
 * 3. Deterministic organic multi-harmonic perimeter contours
 */
export function generateDynamicAreaBoundary(
  center: [number, number],
  areaName: string,
  associatedPoints: [number, number][] = [],
  baseRadiusKm?: number
): [number, number][] {
  const [lat, lng] = center;
  const isWard = /ward|வார்டு/i.test(areaName);
  const effectiveRadius = baseRadiusKm || (isWard ? 0.85 : 1.2);
  const numPoints = 24;
  const seed = hashString(areaName.toLowerCase().replace(/[^a-z0-9]/g, ''));
  const phi1 = ((seed % 100) / 100) * Math.PI * 2;
  const phi2 = (((seed >> 2) % 100) / 100) * Math.PI * 2;
  const phi3 = (((seed >> 4) % 100) / 100) * Math.PI * 2;

  const coords: [number, number][] = [];
  for (let i = 0; i < numPoints; i++) {
    const angle = (i * 2 * Math.PI) / numPoints;
    let r =
      effectiveRadius *
      (1 +
        0.18 * Math.sin(2 * angle + phi1) +
        0.12 * Math.cos(3 * angle + phi2) +
        0.06 * Math.sin(5 * angle + phi3));

    // Dynamically expand radius in direction of any associated kilai or booth points
    for (const [pLat, pLng] of associatedPoints) {
      if (!pLat || !pLng) continue;
      const dLat = (pLat - lat) * 111.139;
      const dLng = (pLng - lng) * 111.139 * Math.cos((lat * Math.PI) / 180);
      const pDist = Math.sqrt(dLat * dLat + dLng * dLng);
      let pAngle = Math.atan2(dLng, dLat);
      if (pAngle < 0) pAngle += 2 * Math.PI;
      const angleDiff = Math.abs(angle - pAngle);
      if (angleDiff < Math.PI / 4 || angleDiff > (7 * Math.PI) / 4) {
        r = Math.max(r, pDist + 0.35);
      }
    }

    const dLatDeg = (r * Math.cos(angle)) / 111.139;
    const dLngDeg = (r * Math.sin(angle)) / (111.139 * Math.cos((lat * Math.PI) / 180));
    coords.push([Number((lat + dLatDeg).toFixed(5)), Number((lng + dLngDeg).toFixed(5))]);
  }
  // Close the loop
  coords.push(coords[0]);
  return coords;
}

/**
 * Gets geographic data (center & perimeter boundary) for an area/panchayat.
 * Dynamically calculated for all areas in MASTER_AREAS_DATA.
 */
export function getAreaGeoData(
  areaName: string,
  associatedKilais: any[] = []
): {
  center: [number, number];
  boundaryCoords: [number, number][];
  description?: string;
  isSurveyed: boolean;
} {
  const norm = normalizeAreaKey(areaName);
  const canonicalKey = AREA_ALIASES[norm] || norm;

  // Extract any known coordinates from associated kilais or booths
  const associatedPoints: [number, number][] = [];
  associatedKilais.forEach((k: any) => {
    if (k.latitude && k.longitude) {
      associatedPoints.push([Number(k.latitude), Number(k.longitude)]);
    }
    (k.booths || []).forEach((b: any) => {
      if (b.latitude && b.longitude) {
        associatedPoints.push([Number(b.latitude), Number(b.longitude)]);
      }
    });
  });

  // Check surveyed reference GIS repository (official Google Maps boundary for Karaikadu)
  if (UNION_VILLAGE_GEO_DATA[canonicalKey]) {
    const data = UNION_VILLAGE_GEO_DATA[canonicalKey];
    return {
      center: data.center,
      boundaryCoords: data.boundaryCoords,
      description: data.description,
      isSurveyed: true,
    };
  }

  // Look up in MASTER_AREAS_DATA (supports English, Tamil, aliases, or translated name)
  let master = MASTER_AREAS_DATA.find(
    (item) => normalizeAreaKey(item.english) === canonicalKey || normalizeAreaKey(item.tamil) === canonicalKey
  );

  if (!master) {
    const enName = normalizeAreaKey(translateAreaToEnglish(areaName));
    master = MASTER_AREAS_DATA.find((item) => normalizeAreaKey(item.english) === enName);
  }

  const center: [number, number] = master?.center || [11.690383964049264, 79.74372006471056];
  const boundaryCoords = generateDynamicAreaBoundary(center, areaName, associatedPoints);

  return {
    center,
    boundaryCoords,
    description: `Administrative boundary dynamically calculated for ${areaName} in Kurinjipadi / Cuddalore region.`,
    isSurveyed: false,
  };
}

/**
 * Translates an area / panchayat name to Tamil.
 */
export function translateAreaToTamil(area: string): string {
  if (!area || typeof area !== 'string') return area;
  const trimmed = area.trim();

  // If already Tamil
  if (/[\u0B80-\u0BFF]/.test(trimmed)) {
    return trimmed;
  }

  const norm = normalizeAreaKey(trimmed);
  const canonical = AREA_ALIASES[norm] || norm;

  const match = MASTER_AREAS_DATA.find((item) => normalizeAreaKey(item.english) === canonical);
  if (match) return match.tamil;

  // Ward match
  const wardMatch = trimmed.match(/^ward[\s\-_.]*([0-9]+)$/i);
  if (wardMatch) return `வார்டு ${wardMatch[1]}`;

  return area;
}

/**
 * Translates an area / panchayat name to English.
 */
export function translateAreaToEnglish(area: string): string {
  if (!area || typeof area !== 'string') return area;
  const trimmed = area.trim();

  const norm = normalizeAreaKey(trimmed);
  const canonical = AREA_ALIASES[norm] || norm;

  // Match in MASTER_AREAS_DATA
  const match = MASTER_AREAS_DATA.find(
    (item) => normalizeAreaKey(item.tamil) === canonical || normalizeAreaKey(item.english) === canonical
  );
  if (match) return match.english;

  // Ward match (English or Tamil)
  const wardMatch = trimmed.match(/^(?:வார்டு|ward)[\s\-_.]*([0-9]+)$/i);
  if (wardMatch) return `Ward ${wardMatch[1]}`;

  // Capitalize words as fallback
  return trimmed.replace(/\b\w/g, (c) => c.toUpperCase());
}

/**
 * Returns formatted bilingual representation: e.g. { en: "Karaikadu", ta: "காரைக்காடு" }
 */
export function getAreaBilingualNames(area: string): { en: string; ta: string } {
  const isTa = /[\u0B80-\u0BFF]/.test(area);
  if (isTa) {
    return {
      en: translateAreaToEnglish(area),
      ta: area,
    };
  }
  return {
    en: translateAreaToEnglish(area),
    ta: translateAreaToTamil(area),
  };
}

/**
 * Checks whether two area strings match (handling cases, spaces, Tamil vs English, and aliases).
 */
export function isAreaNameMatch(areaA?: string, areaB?: string): boolean {
  if (!areaA || !areaB) return false;
  const normA = normalizeAreaKey(areaA);
  const normB = normalizeAreaKey(areaB);

  if (normA === normB) return true;

  const canA = AREA_ALIASES[normA] || normA;
  const canB = AREA_ALIASES[normB] || normB;
  if (canA === canB) return true;

  const enA = normalizeAreaKey(translateAreaToEnglish(areaA));
  const enB = normalizeAreaKey(translateAreaToEnglish(areaB));
  if (enA === enB) return true;

  const canEnA = AREA_ALIASES[enA] || enA;
  const canEnB = AREA_ALIASES[enB] || enB;
  return canEnA === canEnB;
}

/**
 * Creates a URL-safe slug for an area.
 */
export function createAreaSlug(area: string): string {
  const en = translateAreaToEnglish(area);
  return en.toLowerCase().replace(/[\s\-_]+/g, '-').replace(/[^a-z0-9\-]/g, '');
}
