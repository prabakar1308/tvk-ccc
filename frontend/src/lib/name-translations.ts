function normalizeKey(str: string): string {
  return str.toLowerCase().replace(/[\s\-_.,/()]+/g, '').trim();
}

export function phoneticTransliterateWord(word: string): string {
  const w = word.toLowerCase().trim();
  if (!w) return '';

  let result = '';
  let i = 0;

  while (i < w.length) {
    // 1. Initial vowel
    if (i === 0 && /[aeiou]/.test(w[i])) {
      if (i + 1 < w.length) {
        const twoV = w.slice(i, i + 2);
        if (INITIAL_VOWELS[twoV]) {
          result += INITIAL_VOWELS[twoV];
          i += 2;
          continue;
        }
      }
      result += INITIAL_VOWELS[w[i]] || w[i];
      i += 1;
      continue;
    }

    // 2. Consonants
    let c = '';
    let cLen = 0;
    if (i + 1 < w.length) {
      const two = w.slice(i, i + 2);
      if (CONSONANT_MAP[two]) {
        c = CONSONANT_MAP[two];
        cLen = 2;
      }
    }
    if (!c && CONSONANT_MAP[w[i]]) {
      c = CONSONANT_MAP[w[i]];
      cLen = 1;
    }

    if (c) {
      i += cLen;
      // Look ahead for vowel sign
      let vSign: string | null = null;
      let vLen = 0;
      if (i + 1 < w.length) {
        const twoV = w.slice(i, i + 2);
        if (VOWEL_SIGNS[twoV] !== undefined) {
          vSign = VOWEL_SIGNS[twoV];
          vLen = 2;
        }
      }
      if (vSign === null && i < w.length && VOWEL_SIGNS[w[i]] !== undefined) {
        vSign = VOWEL_SIGNS[w[i]];
        vLen = 1;
      }

      if (vSign !== null) {
        const base = c.replace('்', '');
        result += base + vSign;
        i += vLen;
      } else {
        result += c;
      }
      continue;
    }

    result += w[i];
    i++;
  }

  return result;
}

function translateSingleWord(word: string): string {
  if (!word || typeof word !== 'string') return word;
  const trimmed = word.trim();
  if (/[\u0B80-\u0BFF]/.test(trimmed)) return trimmed;

  const plainKey = trimmed.toLowerCase();
  if (KNOWN_NAME_TRANSLATIONS_TA[plainKey]) {
    return KNOWN_NAME_TRANSLATIONS_TA[plainKey];
  }

  const normKey = normalizeKey(trimmed);
  if (KNOWN_NAME_TRANSLATIONS_TA[normKey]) {
    return KNOWN_NAME_TRANSLATIONS_TA[normKey];
  }

  // Compound name matching with known suffixes
  for (const { en, ta } of NAME_SUFFIXES) {
    if (plainKey.length > en.length + 2 && plainKey.endsWith(en)) {
      const prefix = plainKey.slice(0, -en.length);
      const prefixTa = translateSingleWord(prefix);
      if (prefixTa && prefixTa !== prefix) {
        return prefixTa + ta;
      }
    }
  }

  // Phonetic fallback
  const phonetic = phoneticTransliterateWord(trimmed);
  return phonetic || trimmed;
}

export function translatePersonNameToTamil(name: string): string {
  if (!name || typeof name !== 'string') return name;

  const trimmed = name.trim();

  // If already in Tamil script, preserve as is
  if (/[\u0B80-\u0BFF]/.test(trimmed)) {
    return trimmed;
  }

  // Check direct full string lookup
  const plainKey = trimmed.toLowerCase();
  if (KNOWN_NAME_TRANSLATIONS_TA[plainKey]) {
    return KNOWN_NAME_TRANSLATIONS_TA[plainKey];
  }
  const normKey = normalizeKey(trimmed);
  if (KNOWN_NAME_TRANSLATIONS_TA[normKey]) {
    return KNOWN_NAME_TRANSLATIONS_TA[normKey];
  }

  // Handle Trailing Initial: e.g. "Mohan G", "Rajkumar D", "Anbarasi.S", "Agilan K."
  const trailingMatch = trimmed.match(/^(.*?)[.\s]+([a-zA-Z])\.?$/);
  if (trailingMatch) {
    const mainName = trailingMatch[1].trim();
    const letter = trailingMatch[2].toLowerCase();
    if (INITIALS_LETTERS_TA[letter]) {
      const translatedMain = translatePersonNameToTamil(mainName);
      return `${translatedMain} ${INITIALS_LETTERS_TA[letter]}`;
    }
  }

  // Handle Leading Initials: e.g. "P. Mohan", "K. Agilan", "Sa. Sachchidanantham", "Ae.vi.vijayagumar"
  const initialMatch = trimmed.match(/^(([a-zA-Z]{1,3}\.\s*)+)(.*)$/);
  if (initialMatch) {
    const rawInitials = initialMatch[1];
    const restName = initialMatch[3].trim();

    const parts = rawInitials.split('.').map((p) => p.trim().toLowerCase()).filter(Boolean);
    const taInitials = parts
      .map((p) => INITIALS_MAP_TA[p] || `${p.toUpperCase()}.`)
      .join(' ');

    const translatedRest = restName ? translatePersonNameToTamil(restName) : '';
    return `${taInitials} ${translatedRest}`.trim();
  }

  // If contains spaces e.g. "Mohan Kumar", "Prakash Raj", "Anbarasi Nataraj"
  if (trimmed.includes(' ')) {
    return trimmed
      .split(/\s+/)
      .map((part) => translatePersonNameToTamil(part))
      .join(' ');
  }

  return translateSingleWord(trimmed);
}

export function translateRoleToTamil(role: string): string {
  if (!role || typeof role !== 'string') return role;

  const trimmed = role.trim();

  if (/[\u0B80-\u0BFF]/.test(trimmed)) {
    return trimmed;
  }

  const plainKey = trimmed.toLowerCase();
  if (KNOWN_ROLE_TRANSLATIONS_TA[plainKey]) {
    return KNOWN_ROLE_TRANSLATIONS_TA[plainKey];
  }

  const normKey = normalizeKey(trimmed);
  if (KNOWN_ROLE_TRANSLATIONS_TA[normKey]) {
    return KNOWN_ROLE_TRANSLATIONS_TA[normKey];
  }

  return role;
}
