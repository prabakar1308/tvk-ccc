export function phoneticTransliterateWord(word: string): string {
  const w = word.toLowerCase().trim();
  if (!w) return '';

  let result = '';
  let i = 0;

  while (i < w.length) {
    // 1. Initial vowel
    if (i === 0 && /[aeiou]/.test(w[i])) {
      if (i + 1 < w.length) {
        const twoV = w.slice(i, i + 2);
        if (INITIAL_VOWELS[twoV]) {
          result += INITIAL_VOWELS[twoV];
          i += 2;
          continue;
        }
      }
      result += INITIAL_VOWELS[w[i]] || w[i];
      i += 1;
      continue;
    }

    // 2. Consonants
    let c = '';
    let cLen = 0;

    // Check 3-letter consonant clusters
    if (i + 2 < w.length) {
      const three = w.slice(i, i + 3);
      if (CONSONANT_3_MAP[three]) {
        c = CONSONANT_3_MAP[three];
        cLen = 3;
      }
    }

    // Check 2-letter consonant clusters
    if (!c && i + 1 < w.length) {
      const two = w.slice(i, i + 2);
      if (CONSONANT_MAP[two]) {
        c = CONSONANT_MAP[two];
        cLen = 2;
      }
    }

    // Check 1-letter consonant
    if (!c && CONSONANT_MAP[w[i]]) {
      cLen = 1;
      // Special Tamil phonetic adjustments:
      // In Tamil, words starting with 'd' use dental 'த்' (த/தி/தே/து) rather than retroflex 'ட்'
      if (i === 0 && w[i] === 'd') {
        c = 'த்';
      } else if (w[i] === 's' && i + 1 < w.length && /[aeiou]/.test(w[i + 1])) {
        // 's' followed by vowel is standard Tamil 'ச்' (ச/சா/சி/சு/செ)
        c = 'ச்';
      } else {
        c = CONSONANT_MAP[w[i]];
      }
    }

    if (c) {
      i += cLen;
      // Look ahead for vowel sign
      let vSign: string | null = null;
      let vLen = 0;
      if (i + 1 < w.length) {
        const twoV = w.slice(i, i + 2);
        if (VOWEL_SIGNS[twoV] !== undefined) {
          vSign = VOWEL_SIGNS[twoV];
          vLen = 2;
        }
      }
      if (vSign === null && i < w.length && VOWEL_SIGNS[w[i]] !== undefined) {
        vSign = VOWEL_SIGNS[w[i]];
        vLen = 1;
      }

      if (vSign !== null) {
        const base = c.replace('்', '');
        result += base + vSign;
        i += vLen;
      } else {
        result += c;
      }
      continue;
    }

    // Non-initial standalone vowel handling (prevents raw English vowels leaking into Tamil)
    if (/[aeiou]/.test(w[i])) {
      if (i + 1 < w.length) {
        const twoV = w.slice(i, i + 2);
        if (MEDIAL_VOWELS[twoV]) {
          result += MEDIAL_VOWELS[twoV];
          i += 2;
          continue;
        }
      }
      result += MEDIAL_VOWELS[w[i]] || w[i];
      i += 1;
      continue;
    }

    result += w[i];
    i++;
  }

  return result;
}

function translateSingleWord(word: string): string {
  if (!word || typeof word !== 'string') return word;
  const trimmed = word.trim();
  if (/[\u0B80-\u0BFF]/.test(trimmed)) return trimmed;

  // Single letter initial in word form
  if (trimmed.length === 1 && /[a-zA-Z]/.test(trimmed)) {
    return INITIALS_LETTERS_TA[trimmed.toLowerCase()] || trimmed;
  }

  const plainKey = trimmed.toLowerCase();
  if (KNOWN_NAME_TRANSLATIONS_TA[plainKey]) {
    return KNOWN_NAME_TRANSLATIONS_TA[plainKey];
  }

  const normKey = normalizeKey(trimmed);
  if (KNOWN_NAME_TRANSLATIONS_TA[normKey]) {
    return KNOWN_NAME_TRANSLATIONS_TA[normKey];
  }

  // Compound name matching with known suffixes
  for (const { en, ta } of NAME_SUFFIXES) {
    if (plainKey.length > en.length + 2 && plainKey.endsWith(en)) {
      const prefix = plainKey.slice(0, -en.length);
      const prefixTa = translateSingleWord(prefix);
      if (prefixTa && prefixTa !== prefix) {
        return prefixTa + ta;
      }
    }
  }

  // Phonetic fallback
  const phonetic = phoneticTransliterateWord(trimmed);
  return phonetic || trimmed;
}

export function translatePersonNameToTamil(name: string): string {
  if (!name || typeof name !== 'string') return name;

  const trimmed = name.trim();

  // If already in Tamil script, preserve as is
  if (/[\u0B80-\u0BFF]/.test(trimmed)) {
    return trimmed;
  }

  // Single letter initial
  if (trimmed.length === 1 && /[a-zA-Z]/.test(trimmed)) {
    return INITIALS_LETTERS_TA[trimmed.toLowerCase()] || trimmed;
  }

  // Check direct full string lookup
  const plainKey = trimmed.toLowerCase();
  if (KNOWN_NAME_TRANSLATIONS_TA[plainKey]) {
    return KNOWN_NAME_TRANSLATIONS_TA[plainKey];
  }
  const normKey = normalizeKey(trimmed);
  if (KNOWN_NAME_TRANSLATIONS_TA[normKey]) {
    return KNOWN_NAME_TRANSLATIONS_TA[normKey];
  }

  // Handle Trailing Initial: e.g. "Mohan G", "Rajkumar D", "Anbarasi.S", "Agilan K.", "Karthik K"
  const trailingMatch = trimmed.match(/^(.*?)[.\s]+([a-zA-Z])\.?$/);
  if (trailingMatch) {
    const mainName = trailingMatch[1].trim();
    const letter = trailingMatch[2].toLowerCase();
    if (INITIALS_LETTERS_TA[letter]) {
      const translatedMain = translatePersonNameToTamil(mainName);
      return `${translatedMain} ${INITIALS_LETTERS_TA[letter]}`;
    }
  }

  // Handle Leading Initials with dot: e.g. "P. Mohan", "K. Agilan", "Sa. Sachchidanantham", "Ae.vi.vijayagumar"
  const initialMatch = trimmed.match(/^(([a-zA-Z]{1,3}\.\s*)+)(.*)$/);
  if (initialMatch) {
    const rawInitials = initialMatch[1];
    const restName = initialMatch[3].trim();

    const parts = rawInitials.split('.').map((p) => p.trim().toLowerCase()).filter(Boolean);
    const taInitials = parts
      .map((p) => INITIALS_MAP_TA[p] || `${p.toUpperCase()}.`)
      .join(' ');

    const translatedRest = restName ? translatePersonNameToTamil(restName) : '';
    return `${taInitials} ${translatedRest}`.trim();
  }

  // Handle Leading Single-Letter Initial with space (without dot): e.g. "K Karthik", "M Ganesan", "P Prakash"
  const leadingSpaceMatch = trimmed.match(/^([a-zA-Z])\s+([a-zA-Z].*)$/);
  if (leadingSpaceMatch) {
    const letter = leadingSpaceMatch[1].toLowerCase();
    const restName = leadingSpaceMatch[2].trim();
    if (INITIALS_MAP_TA[letter]) {
      return `${INITIALS_MAP_TA[letter]} ${translatePersonNameToTamil(restName)}`.trim();
    }
  }

  // If contains spaces e.g. "Mohan Kumar", "Prakash Raj", "Anbarasi Nataraj"
  if (trimmed.includes(' ')) {
    return trimmed
      .split(/\s+/)
      .map((part) => translatePersonNameToTamil(part))
      .join(' ');
  }

  return translateSingleWord(trimmed);
}

export function translateRoleToTamil(role: string): string {
  if (!role || typeof role !== 'string') return role;

  const trimmed = role.trim();

  if (/[\u0B80-\u0BFF]/.test(trimmed)) {
    return trimmed;
  }

  const plainKey = trimmed.toLowerCase();
  if (KNOWN_ROLE_TRANSLATIONS_TA[plainKey]) {
    return KNOWN_ROLE_TRANSLATIONS_TA[plainKey];
  }

  const normKey = normalizeKey(trimmed);
  if (KNOWN_ROLE_TRANSLATIONS_TA[normKey]) {
    return KNOWN_ROLE_TRANSLATIONS_TA[normKey];
  }

  return role;
}

/**
 * Checks if a role is a Primary Wing Coordinator (English or Tamil)
 */
export function isCoordinatorRole(role?: string | null): boolean {
  if (!role || typeof role !== 'string') return false;
  const upper = role.toUpperCase().trim();
  if (upper === 'COORDINATOR') return true;
  // Tamil: 'ஒருங்கிணைப்பாளர்' (exclude 'இணை ஒருங்கிணைப்பாளர்' which is Co-coordinator)
  if (role.includes('ஒருங்கிணைப்பாளர்') && !role.includes('இணை')) return true;
  return false;
}

/**
 * Checks if a role is a Co-Coordinator (English or Tamil)
 */
export function isCoCoordinatorRole(role?: string | null): boolean {
  if (!role || typeof role !== 'string') return false;
  const upper = role.toUpperCase().trim();
  if (
    upper === 'CO_COORDINATOR' ||
    upper === 'CO-COORDINATOR' ||
    upper === 'COCOORDINATOR' ||
    upper === 'CO COORDINATOR'
  ) {
    return true;
  }
  // Tamil: 'இணை ஒருங்கிணைப்பாளர்'
  if (role.includes('இணை ஒருங்கிணைப்பாளர்') || (role.includes('இணை') && role.includes('ஒருங்கிணைப்பாளர்'))) {
    return true;
  }
  return false;
}

/**
 * Normalizes a wing role to its canonical enum ('COORDINATOR' | 'CO_COORDINATOR')
 */
export function getCanonicalWingRole(role?: string | null): 'COORDINATOR' | 'CO_COORDINATOR' {
  if (isCoCoordinatorRole(role)) return 'CO_COORDINATOR';
  return 'COORDINATOR';
}

/**
 * Checks if a role is a Secretary (English or Tamil, excluding Joint/Deputy)
 */
export function isSecretaryRole(role?: string | null): boolean {
  if (!role || typeof role !== 'string') return false;
  const upper = role.toUpperCase().trim();
  if (upper === 'SECRETARY' || upper === 'DISTRICT_SECRETARY') return true;
  // Tamil: 'செயலாளர்' (exclude 'இணைச் செயலாளர்' / 'துணைச் செயலாளர்')
  if (role.includes('செயலாளர்') && !role.includes('இணை') && !role.includes('துணை')) return true;
  return false;
}

